import pandas as pd
df=pd.read_excel("Online Retail.xlsx")
print("First five Rows:")
print(df.head())
print("\nDataset Shape:")
print(df.shape)
print("\nColumn Names:")
print(df.columns.tolist())
print("\n --- Dataset Shape---")
print("Rows and columns:",df.shape)
print("Number of rows:",df.shape[0])
print("Number of columns:",df.shape[1])
print("\n---Data types---")
print(df.dtypes)
print("\n--- Dataset Information---")
df.info()
print("\n ---Missing values---")
print(df.isnull().sum())
print("\n ---Duplicate rows ---")
print(df.duplicated().sum())
print("\n--- Missing Value Analysis---")
missing_count=df.isnull().sum()
missing_percent=(missing_count/len(df))*100
missing_report=pd.DataFrame({
    "Missing_Count":missing_count,
    "Missing_Percentage":missing_percent.round(2)
})
print(missing_report.sort_values(by="Missing_Count",ascending=False))
print("\n--- Numemrical summary---")
print(df.describe())
print("minimum quantity:",df["Quantity"].min())
print("Maximum quantity:",df["Quantity"].max())
print("Minimum Unit Price:",df["UnitPrice"].min())
print("Maximum Unit Price:",df["UnitPrice"].max())
print("\n --- Duplicate Record Examples---")
duplicates=df[df.duplicated(keep=False)]
print(duplicates.head(10))
print((df["Quantity"]<0).sum())
df["Sales"] = df["Quantity"] * df["UnitPrice"]
print("\n--- SALES SUMMARY ---")
print(df["Sales"].describe())
df["InvoiceNo"] = df["InvoiceNo"].astype(str)
cancelled = df[
    df["InvoiceNo"].str.startswith("C", na=False)
]
print("\n--- CANCELLATION ANALYSIS ---")
print("Cancellation rows:", len(cancelled))
print("Unique cancellation invoices:",cancelled["InvoiceNo"].nunique())
negative_prices = df[df["UnitPrice"] < 0]
zero_prices = df[df["UnitPrice"] == 0]
print("\n--- PRICE QUALITY CHECK ---")
print("Negative price rows:", len(negative_prices))
print("Zero price rows:", len(zero_prices))
print("\nExamples of negative price records:")
print(negative_prices[["InvoiceNo", "Description", "Quantity", "UnitPrice"]].head(5))
positive_sales = df[(df["Quantity"] > 0) & (df["UnitPrice"] > 0)].copy()
positive_sales["Sales"] = (positive_sales["Quantity"] * positive_sales["UnitPrice"]
)
country_sales = (positive_sales.groupby("Country")["Sales"].sum().sort_values(ascending=False))
print("\n--- TOP 10 COUNTRIES BY POSITIVE SALES VALUE ---")
print(country_sales.head(10).round(2))
print("\n--- NEGATIVE PRICE DETAILS ---")
print(df.loc[df["UnitPrice"] < 0,["InvoiceNo", "Description", "Quantity","InvoiceDate", "UnitPrice", "Country"]])
print("\n--- DATE RANGE ---")
print("First invoice date:", df["InvoiceDate"].min())
print("Last invoice date:", df["InvoiceDate"].max())
sales_data = df[(df["Quantity"] > 0) & (df["UnitPrice"] > 0)].copy()
sales_data["Sales"] = (sales_data["Quantity"] * sales_data["UnitPrice"])
sales_data["Month"] = (sales_data["InvoiceDate"].dt.to_period("M"))

monthly_sales = sales_data.groupby("Month")["Sales"].sum()

print("\n--- MONTHLY SALES ---")
print(monthly_sales.round(2))
missing_report.to_csv("missing_values_report.csv")
country_sales.head(10).to_csv("top_10_countries.csv")
monthly_sales.to_csv("monthly_sales.csv", header=["Sales"])
print("\nEDA output files saved successfully!")